/// Unauthenticated credential routes. Mounted behind the strict per-IP limiter.
pub fn sensitive_router() -> axum::Router<crate::AppState> {
    use axum::routing::post;
    axum::Router::new()
        .route("/auth/login", post(login))
        .route("/auth/verify-2fa", post(verify_2fa))
        .route("/auth/verify-recovery", post(verify_recovery))
        .route("/auth/request-password-reset", post(request_password_reset))
        .route("/auth/reset-password", post(reset_password))
}

/// Authenticated auth routes. Not on the strict per-IP limiter.
///
/// `/auth/me` and `/auth/profile` are keyed per user id with a generous quota.
/// `DELETE /auth/rate-limit/:login` clears a temporary per-identifier block.
pub fn session_router() -> axum::Router<crate::AppState> {
    use axum::routing::{delete, get, post, put};
    axum::Router::new()
        .route("/auth/me", get(me))
        .route("/auth/profile", put(super::users::update_my_profile))
        .route("/auth/change-password", post(change_password))
        .route("/auth/setup-2fa", post(setup_2fa))
        .route("/auth/disable-2fa", post(disable_2fa))
        .route("/auth/rate-limit/:login", delete(clear_auth_rate_limit))
}

#[derive(Serialize)]
struct LoginIdentifierAudit<'a> {
    login: &'a str,
}

#[derive(Clone, Copy, Serialize)]
struct TwoFaVerifyAttemptAudit {
    trust_device: bool,
    has_device_id: bool,
}

#[derive(Serialize)]
struct PasswordChangedViaResetAudit {
    source: &'static str,
}

#[derive(Serialize)]
struct UserIdAudit {
    user_id: i64,
}

/// Login request body
#[derive(Deserialize, Validate, ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct LoginRequest {
    /// Username or login
    #[validate(length(min = 1, message = "username is required"))]
    pub username: String,
    /// Password
    #[validate(custom(function = "crate::models::secret::validate_nonempty_secret"))]
    #[schema(value_type = String)]
    pub password: PlaintextPassword,
    /// Device ID (optional, for bypassing 2FA if device is already trusted)
    pub device_id: Option<String>,
}

/// Login response with JWT token
#[derive(Serialize, ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct LoginResponse {
    /// JWT access token (None if 2FA is required)
    pub token: Option<String>,
    /// Token type (always "Bearer")
    pub token_type: String,
    /// Token expiration time in seconds
    pub expires_in: i64,
    /// User information
    pub user: UserInfo,
    /// Whether 2FA verification is required
    pub requires_2fa: bool,
    /// 2FA method if required ("totp" or "email")
    pub two_factor_method: Option<String>,
    /// Device ID generated by server (only present if 2FA is required, client should store and reuse it)
    pub device_id: Option<String>,
    /// When true the user must change their password before continuing
    pub must_change_password: bool,
}

/// User information returned after login
#[serde_as]
#[derive(Serialize, ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct UserInfo {
    /// User ID
    #[serde_as(as = "DisplayFromStr")]
    #[schema(value_type = String)]
    pub id: i64,
    /// Login/username (primary identifier, required)
    pub login: String,
    /// Same value as `login`. Profile clients read `username`.
    pub username: String,
    /// Email (optional)
    pub email: Option<String>,
    /// First name
    pub firstname: Option<String>,
    /// Last name
    pub lastname: Option<String>,
    /// Street address
    pub addr_street: Option<String>,
    /// Zip code
    pub addr_zip_code: Option<i32>,
    /// City
    pub addr_city: Option<String>,
    /// Phone number
    pub phone: Option<String>,
    /// Birth date (ISO `YYYY-MM-DD`)
    pub birthdate: Option<NaiveDate>,
    /// Account type name
    pub account_type: String,
    /// Public type name (`child`, `adult`, …). Null when the patron has none.
    pub public_type: Option<String>,
    /// Linked legal guardian. Null when the patron has none.
    #[serde_as(as = "Option<DisplayFromStr>")]
    #[schema(value_type = Option<String>)]
    pub guardian_id: Option<i64>,
    /// Preferred language
    pub language: Language,
    /// Derived: `eventsConsentAt` is set.
    pub events_consent: bool,
    /// When the patron consented to event announcements. Null means no consent.
    pub events_consent_at: Option<DateTime<Utc>>,
    /// Route that recorded the latest consent change.
    pub events_consent_source: Option<EventsConsentSource>,
}

impl UserInfo {
    fn from_user(user: &crate::models::user::User, public_type_name: Option<String>) -> Self {
        let login = user.login.clone().unwrap_or_default();
        Self {
            id: user.id,
            login: login.clone(),
            username: login,
            email: user.email.clone(),
            firstname: user.firstname.clone(),
            lastname: user.lastname.clone(),
            addr_street: user.addr_street.clone(),
            addr_zip_code: user.addr_zip_code,
            addr_city: user.addr_city.clone(),
            phone: user.phone.clone(),
            birthdate: user.birthdate,
            account_type: user.account_type.to_string(),
            public_type: public_type_name,
            guardian_id: user.guardian_id,
            language: user.language.unwrap_or(Language::French),
            events_consent: user.events_consent,
            events_consent_at: user.events_consent_at,
            events_consent_source: user.events_consent_source,
        }
    }
}

pub(crate) async fn user_info_for(
    state: &crate::AppState,
    user: &crate::models::user::User,
) -> AppResult<UserInfo> {
    let public_type = match user.public_type {
        Some(id) => match state.services.public_types.get_by_id(id).await {
            Ok(public_type) => Some(public_type.name),
            Err(AppError::NotFound(_)) => None,
            Err(err) => return Err(err),
        },
        None => None,
    };
    Ok(UserInfo::from_user(user, public_type))
}

/// Login endpoint - authenticate and get JWT token
#[utoipa::path(
    post,
    path = "/auth/login",
    tag = "auth",
    request_body = LoginRequest,
    responses(
        (status = 200, description = "Login successful", body = LoginResponse),
        (status = 401, description = "Invalid credentials", body = ErrorResponse),
        (status = 429, description = "Too many attempts for this login or IP", body = RateLimitedBody)
    )
)]
pub async fn login(
    State(state): State<crate::AppState>,
    ClientIp(ip): ClientIp,
    Extension(attempts): Extension<Arc<AuthAttemptLimiter>>,
    ValidatedJson(request): ValidatedJson<LoginRequest>,
) -> AppResult<Json<LoginResponse>> {
    let identifier = normalize_identifier(&request.username);
    if let Some(retry_after) = attempts.retry_after(&identifier) {
        return Err(AppError::RateLimited { retry_after });
    }

    let login_result = state
        .services
        .users
        .authenticate(
            &request.username,
            &request.password,
            request.device_id.as_deref(),
        )
        .await;

    match &login_result {
        Ok((_, user)) => {
            attempts.clear(&identifier);
            state.services.audit.log(
                audit::event::AUTH_LOGIN_SUCCESS,
                Some(user.id),
                Some("user"),
                Some(user.id),
                ip.clone(),
                Some(LoginIdentifierAudit {
                    login: request.username.as_str(),
                }),
                audit::AuditLogMeta::success(),
            );
        }
        Err(e) => {
            if matches!(e, AppError::Authentication(_)) {
                attempts.record_failure(&identifier);
            }
            state.services.audit.log(
                audit::event::AUTH_LOGIN_FAILED,
                None,
                None,
                None,
                ip.clone(),
                Some(LoginIdentifierAudit {
                    login: request.username.as_str(),
                }),
                audit::AuditLogMeta::from_app_error(e),
            );
        }
    }

    let (token, user) = login_result?;

    let requires_2fa = token.is_none() && user.two_factor_enabled.unwrap_or(false);
    let two_factor_method = if requires_2fa {
        user.two_factor_method.clone()
    } else {
        None
    };

    // Generate device_id if 2FA is required (client will store and reuse it)
    // reuse request.device_id if provided or generate a new one if not provided
    let device_id = request.device_id.clone().or_else(|| {
        if requires_2fa {
            use uuid::Uuid;
            Some(Uuid::new_v4().to_string())
        } else {
            None
        }
    });

    // If 2FA is enabled and method is email, send code
    if requires_2fa && two_factor_method.as_deref() == Some("email") {
        if let Some(ref email) = user.email {
            use rand::Rng;
            // Generate code before await to avoid Send issues
            let code = {
                let mut rng = rand::thread_rng();
                format!("{:06}", rng.gen_range(100000..999999))
            };

            // Store code in Redis with 10 minutes expiration
            state
                .services
                .redis
                .store_2fa_code(user.id, &code, 600)
                .await?;

            // Send code via email
            match state
                .services
                .email
                .send_2fa_code(email, &code, user.language)
                .await
            {
                Ok(()) => {
                    state.services.audit.log(
                        audit::event::EMAIL_2FA_CODE_SENT,
                        Some(user.id),
                        Some("user"),
                        Some(user.id),
                        ip.clone(),
                        Some(serde_json::json!({ "to": email.as_str() })),
                        audit::AuditLogMeta::success(),
                    );
                }
                Err(e) => {
                    state.services.audit.log(
                        audit::event::EMAIL_2FA_CODE_SENT,
                        Some(user.id),
                        Some("user"),
                        Some(user.id),
                        ip.clone(),
                        Some(serde_json::json!({ "to": email.as_str() })),
                        audit::AuditLogMeta::from_app_error(&e),
                    );
                    return Err(e);
                }
            }
        }
    }

    let must_change_password = user.must_change_password;

    Ok(Json(LoginResponse {
        token,
        token_type: "Bearer".to_string(),
        expires_in: (state.config.users.jwt_expiration_hours * 3600) as i64,
        user: user_info_for(&state, &user).await?,
        requires_2fa,
        two_factor_method,
        device_id,
        must_change_password,
    }))
}

/// Clear the temporary per-identifier sign-in block and reset-request quota.
///
/// Librarian or admin, with `users_rights` write. The value is normalized
/// the same way as login attempts (trim + lowercase).
#[utoipa::path(
    delete,
    path = "/auth/rate-limit/{login}",
    tag = "auth",
    security(("bearer_auth" = [])),
    params(
        ("login" = String, Path, description = "Login or email whose attempt window should be cleared")
    ),
    responses(
        (status = 204, description = "Attempt window cleared (also when it was already empty)"),
        (status = 401, description = "Not authenticated", body = ErrorResponse),
        (status = 403, description = "Staff with users write rights required", body = ErrorResponse)
    )
)]
pub async fn clear_auth_rate_limit(
    State(state): State<crate::AppState>,
    StaffUser(claims): StaffUser,
    ClientIp(ip): ClientIp,
    Extension(attempts): Extension<Arc<AuthAttemptLimiter>>,
    Extension(resets): Extension<Arc<PasswordResetAttemptLimiter>>,
    Path(login): Path<String>,
) -> AppResult<StatusCode> {
    claims.require_write_users()?;
    let identifier = normalize_identifier(&login);
    if identifier.is_empty() {
        return Err(AppError::Validation("login is required".to_string()));
    }
    attempts.clear(&identifier);
    resets.clear(&identifier);
    state.services.audit.log(
        audit::event::AUTH_RATE_LIMIT_CLEARED,
        Some(claims.user_id),
        Some("user"),
        None,
        ip,
        Some(serde_json::json!({ "login": identifier })),
        audit::AuditLogMeta::success(),
    );
    Ok(StatusCode::NO_CONTENT)
}

