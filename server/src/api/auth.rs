/// Verify 2FA code request
#[serde_as]
#[derive(Deserialize, Validate, ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct Verify2FARequest {
    /// User ID (from login response)
    #[serde_as(as = "DisplayFromStr")]
    #[schema(value_type = String)]
    pub user_id: i64,
    /// 2FA code (TOTP or email code)
    #[validate(length(min = 1, message = "code is required"))]
    pub code: String,
    /// Device ID for trusted device feature (optional)
    pub device_id: Option<String>,
    /// Whether to trust this device for 90 days (optional, default: false)
    pub trust_device: Option<bool>,
}

/// Verify 2FA code response
#[derive(Serialize, ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct Verify2FAResponse {
    /// JWT access token
    pub token: String,
    /// Token type (always "Bearer")
    pub token_type: String,
    /// Token expiration time in seconds
    pub expires_in: i64,
}

/// Verify 2FA code endpoint
#[utoipa::path(
    post,
    path = "/auth/verify-2fa",
    tag = "auth",
    request_body = Verify2FARequest,
    responses(
        (status = 200, description = "2FA verification successful", body = Verify2FAResponse),
        (status = 401, description = "Invalid 2FA code", body = ErrorResponse)
    )
)]
pub async fn verify_2fa(
    State(state): State<crate::AppState>,
    ClientIp(ip): ClientIp,
    ValidatedJson(request): ValidatedJson<Verify2FARequest>,
) -> AppResult<Json<Verify2FAResponse>> {
    let trust_device = request.trust_device.unwrap_or(false);
    let verify_ctx = TwoFaVerifyAttemptAudit {
        trust_device,
        has_device_id: request.device_id.is_some(),
    };
    let result = state
        .services
        .users
        .verify_2fa(
            request.user_id,
            &request.code,
            request.device_id.as_deref(),
            trust_device,
        )
        .await;

    match &result {
        Ok(_) => state.services.audit.log(
            audit::event::AUTH_2FA_VERIFIED,
            Some(request.user_id),
            Some("user"),
            Some(request.user_id),
            ip.clone(),
            Some(verify_ctx),
            audit::AuditLogMeta::success(),
        ),
        Err(e) => {
            state.services.audit.log(
                audit::event::AUTH_2FA_FAILED,
                Some(request.user_id),
                Some("user"),
                Some(request.user_id),
                ip.clone(),
                Some(verify_ctx),
                audit::AuditLogMeta::from_app_error(e),
            );
        }
    }

    let token = result?;
    Ok(Json(Verify2FAResponse {
        token,
        token_type: "Bearer".to_string(),
        expires_in: (state.config.users.jwt_expiration_hours * 3600) as i64,
    }))
}

