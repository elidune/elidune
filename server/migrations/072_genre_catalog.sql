-- Genre catalog: shelf codes, localized labels, MARC 655 synonyms (customizable via SQL).
CREATE TABLE IF NOT EXISTS genres (
    code        SMALLINT PRIMARY KEY,
    shelf_code  VARCHAR(16),
    active      BOOLEAN NOT NULL DEFAULT true,
    sort_order  INT NOT NULL DEFAULT 0
);

COMMENT ON TABLE genres IS 'Library genre codes aligned with Genre enum SMALLINT values.';
COMMENT ON COLUMN genres.shelf_code IS 'Call-number prefix when Dewey is absent; NULL = no genre shelf mark.';

CREATE TABLE IF NOT EXISTS genre_labels (
    genre_code  SMALLINT NOT NULL REFERENCES genres(code) ON DELETE CASCADE,
    language    VARCHAR(8) NOT NULL,
    label       TEXT NOT NULL,
    PRIMARY KEY (genre_code, language),
    CONSTRAINT genre_labels_language_chk CHECK (language IN ('fr', 'en', 'de', 'es'))
);

CREATE TABLE IF NOT EXISTS genre_synonyms (
    id               BIGSERIAL PRIMARY KEY,
    genre_code       SMALLINT NOT NULL REFERENCES genres(code) ON DELETE CASCADE,
    term             TEXT NOT NULL,
    term_normalized  TEXT NOT NULL,
    match_kind       TEXT NOT NULL DEFAULT 'exact',
    CONSTRAINT genre_synonyms_match_kind_chk CHECK (match_kind IN ('exact', 'contains')),
    CONSTRAINT genre_synonyms_term_kind_uq UNIQUE (match_kind, term_normalized)
);

CREATE INDEX IF NOT EXISTS idx_genre_synonyms_norm ON genre_synonyms (term_normalized);

